//Guardamos el nombre de una fruta en una variable
//utilizamos el switch para decir que fruta y color es

let fruta = "   Platano";

switch(fruta){
    case "Manzana":
        console.log("Es una manzana roja");
        break;
    case "Platano":
        console.log("Es un platano amarillo");
        break;
    case "Uva":
        console.log("Es una uva morada");
        break;
    default:
        console.log("Fruta no reconocida");

}