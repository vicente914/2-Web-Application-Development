//Guardamos un número del 1 al 3 en una variable
//mostramos con switch que opción ha escogido

let opcion = 2;

switch(opcion){
    case 1:
        console.log("Opción A seleccionada");
        break;
    case 2:
        console.log("Opción B seleccionada");
        break;
    case 3:
        console.log("Opcion C seleccionada");
        break;
    default:
        console.log("Esa opción no existe");
}